"""SQLModel table definitions for TenantEase Khata.

All data in this database is synthetic, generated by ``app.ml.synth``.
"""

from __future__ import annotations

from datetime import date, datetime

from sqlmodel import Field, SQLModel

from app.clock import now


def _demo_now() -> datetime:
    """Row timestamp taken from the demo clock, never the wall clock."""
    return now()


class Property(SQLModel, table=True):
    """A building or property portfolio entry."""

    __tablename__ = "properties"
    id: int | None = Field(default=None, primary_key=True)
    name: str
    locality: str


class Unit(SQLModel, table=True):
    """A single rentable unit inside a property."""

    __tablename__ = "units"
    id: int | None = Field(default=None, primary_key=True)
    property_id: int = Field(foreign_key="properties.id", index=True)
    label: str
    bhk: int
    rent_inr: int
    floor: int


class Tenant(SQLModel, table=True):
    """A synthetic tenant. Names and phones come from Faker en_IN."""

    __tablename__ = "tenants"
    id: int | None = Field(default=None, primary_key=True)
    name: str
    phone: str
    occupation_type: str  # salaried | business | student | gig
    preferred_language: str  # en | hi | hinglish
    preferred_channel: str  # whatsapp | sms | call


class Lease(SQLModel, table=True):
    """A tenancy linking a tenant to a unit over a period."""

    __tablename__ = "leases"
    id: int | None = Field(default=None, primary_key=True)
    unit_id: int = Field(foreign_key="units.id", index=True)
    tenant_id: int = Field(foreign_key="tenants.id", index=True)
    start_date: date
    end_date: date | None = None
    monthly_rent: int
    due_day: int  # 1 | 5 | 10
    deposit: int


class Payment(SQLModel, table=True):
    """One rent payment attempt per lease per cycle month."""

    __tablename__ = "payments"
    id: int | None = Field(default=None, primary_key=True)
    lease_id: int = Field(foreign_key="leases.id", index=True)
    cycle_month: date = Field(index=True)  # first day of the month
    due_date: date
    paid_date: date | None = None
    amount: int
    method: str  # upi | cash | bank_transfer


class Reminder(SQLModel, table=True):
    """A drafted or approved rent reminder message."""

    __tablename__ = "reminders"
    id: int | None = Field(default=None, primary_key=True)
    lease_id: int = Field(foreign_key="leases.id", index=True)
    cycle_month: date
    channel: str
    tone: str
    language: str
    message: str
    status: str = "draft"  # draft | approved
    created_at: datetime = Field(default_factory=_demo_now)
    approved_at: datetime | None = None
    metadata_json: str | None = None


class MaintenanceRequest(SQLModel, table=True):
    """A triaged maintenance complaint raised for a lease."""

    __tablename__ = "maintenance_requests"
    id: int | None = Field(default=None, primary_key=True)
    lease_id: int = Field(foreign_key="leases.id", index=True)
    text: str
    category: str  # plumbing | electrical | appliance | structural | pest | other
    urgency: str  # emergency | soon | routine
    suggested_trade: str
    summary: str
    method: str  # llm | keyword
    forced_emergency: bool = False
    created_at: datetime = Field(default_factory=_demo_now)


class RiskScore(SQLModel, table=True):
    """Cached risk probability for a lease in a cycle."""

    __tablename__ = "risk_scores"
    id: int | None = Field(default=None, primary_key=True)
    lease_id: int = Field(foreign_key="leases.id", index=True)
    cycle_month: date = Field(index=True)
    raw_score: float
    probability: float
    tier: str  # low | medium | high
    prev_cycle_outstanding_days: float = 0.0
    top_factors_json: str = "[]"
    scored_at: datetime = Field(default_factory=_demo_now)


class Meta(SQLModel, table=True):
    """Key/value facts about the seeded data, written by ``app.ml.synth``."""

    __tablename__ = "meta"
    key: str = Field(primary_key=True)
    value: str
